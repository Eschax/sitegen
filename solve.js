// solve.js: a faster drop-in for makefun-site 1.0.0. run(input) returns, for one site's
// input, exactly the output tree makefun-site 1.0.0's build returns: a JSON object of every
// path it writes and that file's text, byte for byte. It is a fresh implementation of the
// behaviour the kit's README.md states (front matter, template dialect, Markdown subset,
// slug rule, report), written for speed: templates are compiled to functions once, Markdown
// inline text is escaped in whole runs, and slugs are memoised. No dependencies, no clock,
// no environment, no randomness, no file access: the output is a function of the input alone.

